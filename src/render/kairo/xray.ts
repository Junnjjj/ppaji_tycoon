/**
 * 조준 중 **가리는 것을 비춰 준다** (K50).
 *
 * ## 문제
 *
 * 아이소메트릭은 카메라 쪽(= `i+j` 가 큰) 오브젝트가 뒤를 덮는다. 그것이 깊이 정렬의
 * 목적이므로 평소엔 옳다. 그런데 배치 조준(K47-③)은 **아직 없는 것**을 보여주는
 * 화면이라, 앞줄 건물이 고스트를 통째로 삼키면 "어디에 놓이는지"를 볼 수가 없다.
 * 지도를 팬해서 각도를 바꿀 수도 없다 — 카메라는 회전하지 않는다 (2:1 다이메트릭 고정).
 *
 * ## 규칙
 *
 * 고스트보다 **앞**(`depth` 가 큼)이면서 고스트의 화면 사각형과 **겹치는** 것만
 * 반투명해진다. 두 조건 모두 필요하다:
 * - 깊이만 보면 화면 반대편의 상관없는 건물까지 흐려져 판이 통째로 뿌예진다
 * - 겹침만 보면 **뒤에 있는 것**(= 이미 고스트에 가려진 것)까지 흐려지는데, 그건
 *   고스트가 이겨서 어차피 안 보이므로 알파만 낭비하고 실루엣이 이중으로 흐려진다
 *
 * ⚠ 깊이 비교의 기준은 **고스트의 실제 깊이**(`depthKey + Z_GHOST`)다. 띠 상수를
 * 건드리지 않는다 — 이 기능은 `alpha` 만 만진다. 같은 칸의 앞벽(`Z_WALL_FRONT` = 3)이
 * 고스트(7)보다 낮아 자동으로 제외되는 것도 이 기준 덕이다.
 *
 * ## 왜 별도 파일인가
 *
 * 판정이 `KairoScene` 안에 있으면 Phaser 없이는 못 재고, 그러면 "검증이 조용히 통과"
 * 목록에 한 줄이 더 붙는다. 순수 함수로 떼어 두면 단위 테스트가 **양성·음성 둘 다**
 * 직접 만들 수 있다 (`xray.test.ts`).
 */

import { STEP_X, STEP_Y } from './iso.js';

/** 화면(월드 텍셀) 축 정렬 사각형. `x1`·`y1` 은 **배타적** 경계다 */
export interface Rect {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}

/**
 * 가리는 것에 주는 알파 (K50).
 *
 * ## 왜 0.42 인가
 *
 * 사용자 요구는 "살짝 투명"이다 — **사라지는 게 아니라 비치는 것**이라야 한다.
 * 실제 화면에서 0.35 · 0.42 · 0.5 를 나란히 보고 골랐다:
 * - `0.50` — 크림 팔레트(밝은 표면) 위에서는 아직 불투명하게 읽힌다. 2층 건물 뒤의
 *   고스트가 여전히 안 보였다
 * - `0.35` — 실루엣이 배경(잔디·포장)에 녹아 "건물이 지워졌다"로 보인다. 그러면
 *   "여기 뭐가 있었지"를 다시 잃는다
 * - `0.42` — 윤곽선(진갈 `#8c5e2b`)이 남아 건물 형태는 읽히면서 안쪽 고스트가 비친다
 *
 * 고스트 자신의 알파(0.62)보다 **낮아야** 한다. 같거나 높으면 겹친 자리에서 어느 쪽이
 * 앞인지가 안 읽힌다.
 */
export const XRAY_ALPHA = 0.42;

/** 겹치나 — 경계가 맞닿기만 한 것은 겹침이 아니다 (배타 경계) */
export function overlaps(a: Rect, b: Rect): boolean {
  return a.x0 < b.x1 && b.x0 < a.x1 && a.y0 < b.y1 && b.y0 < a.y1;
}

/**
 * 이 오브젝트가 조준 대상을 가리나.
 *
 * @param aimDepth 고스트의 깊이 (`depthKey(...) + Z_GHOST`)
 * @param aim      고스트 스프라이트의 화면 사각형
 * @param depth    후보의 깊이
 * @param rect     후보의 화면 사각형
 */
export function occludes(aimDepth: number, aim: Rect, depth: number, rect: Rect): boolean {
  if (depth <= aimDepth) return false;
  return overlaps(aim, rect);
}

/**
 * 발자국 w×d 가 (i, j) 에 놓였을 때 **바닥 마름모**의 화면 바운딩박스.
 *
 * 고스트 스프라이트의 바운딩박스는 이것을 항상 포함한다 (`footprintCanvas` 가
 * `(w+d)·STEP_X` 폭이고 앵커가 bottom-center 이므로) — 그래서 씬은 스프라이트
 * 경계 하나만 쓴다. 이 함수는 **스프라이트가 없는 경우**(바닥 붓 미리보기)와
 * 테스트에서 기대값을 유도할 때 쓴다.
 *
 * `dy` 는 단 리프트(`lift()`)다 — 안 태우면 산 위 조준에서 판정이 8텍셀씩 어긋난다.
 */
export function footprintRect(i: number, j: number, w: number, d: number, dy = 0): Rect {
  return {
    x0: STEP_X * (i - j - d),
    y0: STEP_Y * (i + j) + dy,
    x1: STEP_X * (i - j + w),
    y1: STEP_Y * (i + j + w + d) + dy,
  };
}
