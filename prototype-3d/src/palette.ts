export function paletteToVec3(): Float32Array {
  const arr = new Float32Array(PALETTE_HEX.length * 3);
  PALETTE_HEX.forEach((hex, i) => {
    arr[i * 3] = parseInt(hex.slice(1, 3), 16) / 255;
    arr[i * 3 + 1] = parseInt(hex.slice(3, 5), 16) / 255;
    arr[i * 3 + 2] = parseInt(hex.slice(5, 7), 16) / 255;
  });
  return arr;
}
